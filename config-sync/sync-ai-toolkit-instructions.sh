#!/usr/bin/env bash
#
# Regenerates the config-sync copies of the org-wide ai-toolkit instructions.
#
# ai-toolkit stays the single source of truth: this script copies the files
# that `apm install` materialized into .github/instructions/ to
# config-sync/files/.github/instructions/, so config-sync distributes them to
# every calling repository. Each copy gets a provenance marker with the
# ai-toolkit ref and commit from apm.lock.yaml, right after the front matter:
#
#   <!-- config-sync: source=DevSecNinja/ai-toolkit ref=v0.9.1 commit=<sha> path=<path>; ... -->
#
# Usage:
#   config-sync/sync-ai-toolkit-instructions.sh          # rewrite the copies
#   config-sync/sync-ai-toolkit-instructions.sh --check  # exit 1 on drift

set -euo pipefail

# Org-wide instructions. `devsecninja-conventions` requires
# `untrusted-repositories`, so the two always ship together.
instructions=(
    devsecninja-conventions
    untrusted-repositories
    writing-style
)

source_repo="DevSecNinja/ai-toolkit"

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
lockfile="${repo_root}/apm.lock.yaml"
src_dir=".github/instructions"
dest_dir="config-sync/files/.github/instructions"

mode="write"
case "${1:-}" in
"") ;;
--check) mode="check" ;;
*)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac

fail() {
    echo "error: $*" >&2
    exit 1
}

[ -f "${lockfile}" ] || fail "${lockfile} not found; run 'apm install' first"

# Prints "<deployed path> <ref> <commit>" for every file that an ai-toolkit
# dependency deploys. Works for a whole-package pin and for subpath pins, which
# APM records as one `dependencies:` entry each.
lock_files() {
    awk -v want="$(tr '[:upper:]' '[:lower:]' <<<"${source_repo}")" '
        function flush(   i) {
            if (tolower(repo) == want)
                for (i = 1; i <= n; i++) print files[i], ref, commit
            repo = ""; ref = ""; commit = ""; n = 0
        }
        /^[^[:space:]-]/ { flush(); in_deps = ($0 ~ /^dependencies:/); next }
        !in_deps { next }
        /^- / { flush() }
        {
            line = $0
            sub(/^- /, "  ", line)
            if (line ~ /^  repo_url: /) { repo = substr(line, 13) }
            else if (line ~ /^  resolved_ref: /) { ref = substr(line, 17) }
            else if (line ~ /^  resolved_commit: /) { commit = substr(line, 20) }
            else if (line ~ /^  - /) { files[++n] = substr(line, 5) }
        }
        END { flush() }
    ' "${lockfile}"
}

deployed="$(lock_files)"
# Inserts the provenance marker after the YAML front matter (or at the top).
render() {
    local src="$1" marker="$2"
    awk -v marker="${marker}" '
        NR == 1 && $0 != "---" { print marker; done = 1 }
        { print }
        NR > 1 && !done && $0 == "---" { print marker; done = 1 }
    ' "${src}"
}

drift=0
tmp="$(mktemp)"
trap 'rm -f "${tmp}"' EXIT

for name in "${instructions[@]}"; do
    rel="${src_dir}/${name}.instructions.md"
    ref="$(awk -v p="${rel}" '$1 == p { print $2; exit }' <<<"${deployed}")"
    commit="$(awk -v p="${rel}" '$1 == p { print $3; exit }' <<<"${deployed}")"
    if [ -z "${ref}" ] || [ -z "${commit}" ]; then
        fail "${rel} is not deployed by ${source_repo} at a resolved ref (see ${lockfile}); run 'apm install'"
    fi
    [ -f "${repo_root}/${rel}" ] || fail "${rel} is missing; run 'apm install'"

    marker="<!-- config-sync: source=${source_repo} ref=${ref} commit=${commit} path=${rel}; generated by DevSecNinja/.github, do not edit (change ai-toolkit instead) -->"
    render "${repo_root}/${rel}" "${marker}" >"${tmp}"

    dest="${repo_root}/${dest_dir}/${name}.instructions.md"
    if [ -f "${dest}" ] && cmp -s "${tmp}" "${dest}"; then
        continue
    fi
    if [ "${mode}" = "check" ]; then
        echo "stale: ${dest_dir}/${name}.instructions.md" >&2
        drift=1
    else
        mkdir -p "$(dirname "${dest}")"
        cp "${tmp}" "${dest}"
        echo "updated: ${dest_dir}/${name}.instructions.md (${ref})"
    fi
done

# Copies of instructions that are no longer distributed.
if [ -d "${repo_root}/${dest_dir}" ]; then
    for dest in "${repo_root}/${dest_dir}"/*.instructions.md; do
        [ -e "${dest}" ] || continue
        name="$(basename "${dest}" .instructions.md)"
        case " ${instructions[*]} " in *" ${name} "*) continue ;; esac
        if [ "${mode}" = "check" ]; then
            echo "orphaned: ${dest_dir}/${name}.instructions.md" >&2
            drift=1
        else
            rm -f "${dest}"
            echo "removed: ${dest_dir}/${name}.instructions.md"
        fi
    done
fi

if [ "${drift}" -ne 0 ]; then
    fail "config-sync copies of the ai-toolkit instructions are out of date; run config-sync/sync-ai-toolkit-instructions.sh"
fi
